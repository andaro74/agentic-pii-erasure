"""Write the fabricated subjects into the real services, and emit ground truth as it goes.

**Ground truth is generated, never labelled** — invariant 8 and
[ADR-020](../../docs/adr/ADR-020-deployed-eval-gate.md).
The placement map is produced by the same pass that performs the writes, from the writes
themselves — each `_write_*` returns what it actually created, and the map is assembled
from those returns. Two failure modes are ruled out by construction:

* **Hand-written ground truth drifts.** A map maintained beside the seeder is a second
  source of truth, and the copy that rots is always the one nobody runs. Here there is no
  second copy: a write that does not happen cannot appear in the map.
* **Ground truth derived from the agent's output measures nothing.** If the map came from
  what discovery found, recall would be 1.0 by definition and ADR-008's gate would be
  decoration. The generator never reads a participant's `discover`.

**Eventual consistency is real against real services**, so the generator waits on explicit
signals rather than sleeping (ROADMAP M4 traps). `time.sleep(2)` is not a consistency
model: it passes on a fast day, fails on a slow one, and teaches a reader the wrong thing.
Each writer therefore confirms its own write is *readable* before reporting it — a strongly
consistent read for DynamoDB, a key probe for S3 Vectors, a count query for Aurora.

**Every writer converges** (V8-7). `make seed` is re-run constantly — after a partial
failure, before an eval, on a fresh subject — so running it twice must leave the same state
as running it once. Two failure modes were live here and they are not equally visible:

* *Loud*: `AdminCreateUser` and `CreateContact` raise on the second run. Annoying, honest,
  and self-announcing.
* *Silent, and far worse*: `PutObject` against a **versioned** bucket adds a version rather
  than replacing one, and an Iceberg `INSERT` appends. After two runs the map would claim
  `objects=3` while the bucket held six — and the recall gate's denominator would be wrong
  with nothing raising. A generator that inflates what it is measuring against is worse
  than one that crashes.

The strategies differ by archetype because the services differ: `upload-bucket` purges the
subject's versions first, `analytics-lake` deletes the subject's rows first, and
`compliance-archive` can do **neither** — Object Lock refuses deletion from everyone
including root, so it writes only what is not already present. The archetype asserting
itself on the seeder is the same lesson the participant teaches, arriving from the other
side.

This module writes to real AWS and is invoked by `make seed`, which is human-only. It is
importable and unit-testable without an account: nothing happens at import, and every
client is injected.
"""

from __future__ import annotations

import json
import re
import time
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from botocore.exceptions import ClientError

from pii_erasure.participants.billing_ledger.handler import execute_with_resume
from pii_erasure.participants.notify_suppression.handler import subject_address
from pii_erasure.participants.vector_index.handler import VECTOR_DIMENSION, vector_key

SEEDS = Path(__file__).resolve().parents[2] / "seeds" / "meridian.json"

#: How long a writer waits for its own write to become readable before giving up. Bounded
#: and loud: a generator that silently proceeded would produce a ground-truth map claiming
#: data that is not there, and every subsequent recall failure would be blamed on the agent.
CONSISTENCY_TIMEOUT_SECONDS = 30.0
_POLL_SECONDS = 0.5


class ConsistencyTimeoutError(RuntimeError):
    """A write did not become readable in time. Never recorded as ground truth."""


@dataclass(frozen=True)
class Placement:
    """What was actually written for one subject in one system."""

    system_id: str
    artifacts: dict[str, int]


@dataclass
class GroundTruth:
    """The placement map. Assembled from writes, never from reads of the agent."""

    tenant_id: str
    subjects: dict[str, list[Placement]] = field(default_factory=dict)

    def record(self, subject_ref: str, placement: Placement) -> None:
        if not placement.artifacts or not any(placement.artifacts.values()):
            return  # nothing written is not a placement, and must not become one
        self.subjects.setdefault(subject_ref, []).append(placement)

    def systems_for(self, subject_ref: str) -> set[str]:
        return {p.system_id for p in self.subjects.get(subject_ref, [])}

    def to_json(self) -> dict[str, Any]:
        return {
            "$comment": (
                "GENERATED by evals/fixtures/generator.py in the same pass that wrote the "
                "data. Do not hand-edit: it is the denominator of the recall gate, and an "
                "edited denominator makes the gate measure nothing (ADR-008)."
            ),
            "tenantId": self.tenant_id,
            "subjects": {
                subject_ref: {
                    p.system_id: p.artifacts for p in sorted(places, key=lambda x: x.system_id)
                }
                for subject_ref, places in sorted(self.subjects.items())
            },
        }


def load_seeds(path: Path = SEEDS) -> dict[str, Any]:
    return dict(json.loads(path.read_text(encoding="utf-8")))


def _await_readable(check: Callable[[], bool], *, what: str) -> None:
    """Block until a write is observable, or fail loudly.

    The alternative — sleeping a fixed interval — is a guess that passes on a fast day and
    produces a wrong ground-truth map on a slow one.
    """
    deadline = time.monotonic() + CONSISTENCY_TIMEOUT_SECONDS
    while time.monotonic() < deadline:
        if check():
            return
        time.sleep(_POLL_SECONDS)
    raise ConsistencyTimeoutError(
        f"{what} did not become readable within {CONSISTENCY_TIMEOUT_SECONDS}s — refusing "
        "to record it as ground truth"
    )


class FixtureGenerator:
    """Writes the seed set into the deployed participants.

    Every client is injected so the assembly logic is unit-testable with no account. The
    writers themselves are exercised by `make seed` against the real stack, which is the
    only place they can be exercised honestly (ADR-017).
    """

    def __init__(self, *, clients: dict[str, Any], config: dict[str, str]) -> None:
        self._clients = clients
        self._config = config

    # ── the pass ─────────────────────────────────────────────────────────────────────

    def run(self, seeds: dict[str, Any] | None = None) -> GroundTruth:
        data = seeds if seeds is not None else load_seeds()
        truth = GroundTruth(tenant_id=data["tenant"]["tenantId"])

        for subject in data["subjects"]:
            subject_ref = subject["subjectRef"]
            for system_id, expected in subject.get("placement", {}).items():
                writer = self._writers().get(system_id)
                if writer is None:
                    raise KeyError(
                        f"no writer for {system_id!r} — the seed file names a system the "
                        "generator cannot write, so its ground truth would be a fiction"
                    )
                written = writer(subject, expected)
                truth.record(subject_ref, Placement(system_id=system_id, artifacts=written))
        return truth

    def _writers(self) -> dict[str, Callable[[dict[str, Any], dict[str, int]], dict[str, int]]]:
        return {
            "cognito-identity": self._write_cognito,
            "profile-store": self._write_profile,
            "billing-ledger": self._write_billing,
            "upload-bucket": self._write_uploads,
            "compliance-archive": self._write_archive,
            "vector-index": self._write_vectors,
            "analytics-lake": self._write_analytics,
            "notify-suppression": self._write_suppression,
        }

    # ── writers ──────────────────────────────────────────────────────────────────────

    def _write_cognito(self, subject: dict[str, Any], expected: dict[str, int]) -> dict[str, int]:
        idp = self._clients["cognito-idp"]
        pool = self._config["userPoolId"]
        try:
            idp.admin_create_user(
                UserPoolId=pool,
                Username=subject["subjectRef"],
                MessageAction="SUPPRESS",
                UserAttributes=[{"Name": "email", "Value": subject["email"]}],
            )
        except ClientError as error:
            if error.response["Error"]["Code"] != "UsernameExistsException":
                raise
            # Already seeded. The declared state is reached either way, which is what
            # `run()` promises; erroring here would make a partial run unrecoverable.
        username = subject["subjectRef"]
        _await_readable(
            lambda: _exists(lambda: idp.admin_get_user(UserPoolId=pool, Username=username)),
            what=f"cognito user {username}",
        )
        return {"users": 1}

    def _write_profile(self, subject: dict[str, Any], expected: dict[str, int]) -> dict[str, int]:
        table = self._clients["dynamodb"].Table(self._config["profileTable"])
        count = expected.get("items", 0)
        injection = subject.get("injection") or {}

        for index in range(count):
            item: dict[str, Any] = {
                "subject_ref": subject["subjectRef"],
                "item_id": f"profile#{index:03d}",
                "tenant": self._config["tenantId"],
                "display_name": subject["displayName"],
                "email": subject["email"],
            }
            if index == 0 and injection:
                # Stored verbatim. Sanitising here would remove the thing the adversarial
                # eval exists to observe (see seeds/meridian.json).
                item[injection["field"]] = injection["payload"]
            table.put_item(Item=item)

        _await_readable(
            lambda: (
                len(
                    table.query(
                        KeyConditionExpression="subject_ref = :s",
                        ExpressionAttributeValues={":s": subject["subjectRef"]},
                        ConsistentRead=True,
                    ).get("Items", [])
                )
                >= count
            ),
            what=f"profile items for {subject['subjectRef']}",
        )
        return {"items": count}

    def _write_billing(self, subject: dict[str, Any], expected: dict[str, int]) -> dict[str, int]:
        written = {
            "customers": expected.get("customers", 0),
            "invoices": expected.get("invoices", 0),
            "invoice_lines": expected.get("invoice_lines", 0),
        }
        self._sql(
            "INSERT INTO public.customers (subject_ref, display_name, email) "
            "VALUES (:subject_ref, :display_name, :email) ON CONFLICT DO NOTHING",
            subject_ref=subject["subjectRef"],
            display_name=subject["displayName"],
            email=subject["email"],
        )
        for invoice in range(written["invoices"]):
            invoice_id = f"{subject['subjectRef']}-inv-{invoice:03d}"
            self._sql(
                "INSERT INTO public.invoices (invoice_id, subject_ref, amount_cents) "
                "VALUES (:invoice_id, :subject_ref, :amount) ON CONFLICT DO NOTHING",
                invoice_id=invoice_id,
                subject_ref=subject["subjectRef"],
                amount=1000 + invoice,
            )
        for line in range(written["invoice_lines"]):
            self._sql(
                "INSERT INTO public.invoice_lines (line_id, invoice_id, description) "
                "VALUES (:line_id, :invoice_id, :description) ON CONFLICT DO NOTHING",
                line_id=f"{subject['subjectRef']}-line-{line:03d}",
                invoice_id=f"{subject['subjectRef']}-inv-{line % max(written['invoices'], 1):03d}",
                description="fabricated line item",
            )
        for hold in subject.get("holds", []):
            self._sql(
                "INSERT INTO public.legal_holds "
                "(hold_id, subject_ref, authority, scope, basis) "
                "VALUES (:hold_id, :subject_ref, :authority, :scope, :basis) "
                "ON CONFLICT DO NOTHING",
                hold_id=hold["holdId"],
                subject_ref=subject["subjectRef"],
                authority=hold["authority"],
                scope=hold["scope"],
                basis=hold["basis"],
            )
        return written

    def _write_uploads(self, subject: dict[str, Any], expected: dict[str, int]) -> dict[str, int]:
        s3 = self._clients["s3"]
        bucket = self._config["uploadBucket"]
        objects = expected.get("objects", 0)
        markers = expected.get("deleteMarkers", 0)

        # Purge first. The bucket is versioned, so re-running without this adds a new
        # version per object per run: the map would say objects=3 while the bucket held
        # six, and the recall denominator would be quietly wrong. Nothing announces that.
        _purge_versions(s3, bucket, f"{subject['subjectRef']}/")

        for index in range(objects):
            s3.put_object(
                Bucket=bucket,
                Key=f"{subject['subjectRef']}/upload-{index:03d}.bin",
                Body=b"fabricated upload",
            )
        for index in range(markers):
            # A prior "deletion" that deleted nothing — the archetype's whole lesson,
            # seeded so discovery has something real to report.
            key = f"{subject['subjectRef']}/tombstoned-{index:03d}.bin"
            s3.put_object(Bucket=bucket, Key=key, Body=b"fabricated upload")
            s3.delete_object(Bucket=bucket, Key=key)
        return {"objects": objects, "deleteMarkers": markers}

    def _write_archive(self, subject: dict[str, Any], expected: dict[str, int]) -> dict[str, int]:
        s3 = self._clients["s3"]
        ddb = self._clients["dynamodb"]
        bucket = self._config["archiveBucket"]
        objects = expected.get("lockedObjects", 0)

        # The purge that `_write_uploads` performs is *impossible* here: COMPLIANCE-mode
        # Object Lock refuses deletion from everyone including root until retention
        # expires. So the only idempotent move is to write what is not already there.
        # This is the archetype asserting itself on the seeder, which is fitting.
        existing = s3.list_objects_v2(Bucket=bucket, Prefix=f"{subject['subjectRef']}/").get(
            "KeyCount", 0
        )
        for index in range(existing, objects):
            s3.put_object(
                Bucket=bucket,
                Key=f"{subject['subjectRef']}/statement-{index:03d}.enc",
                Body=b"fabricated ciphertext",
            )
        if expected.get("wrappedDeks"):
            ddb.Table(self._config["dekRegistryTable"]).put_item(
                Item={
                    "subject_ref": subject["subjectRef"],
                    "wrapped_dek": b"fabricated-wrapped-dek",
                }
            )
        return {"lockedObjects": objects, "wrappedDeks": expected.get("wrappedDeks", 0)}

    def _write_vectors(self, subject: dict[str, Any], expected: dict[str, int]) -> dict[str, int]:
        vectors = self._clients["s3vectors"]
        count = expected.get("vectors", 0)
        payload = [
            {
                "key": vector_key(subject["subjectRef"], index),
                "data": {"float32": [0.01 * (index + 1)] * VECTOR_DIMENSION},
                # Metadata is a PII surface. The pseudonymous handle and a non-identifying
                # source kind only — never bio text, never a name, never an address.
                "metadata": {"subjectRef": subject["subjectRef"], "source": "profile"},
            }
            for index in range(count)
        ]
        for start in range(0, len(payload), 500):  # PutVectors caps at 500
            vectors.put_vectors(
                vectorBucketName=self._config["vectorBucket"],
                indexName=self._config["vectorIndex"],
                vectors=payload[start : start + 500],
            )
        if count:
            _await_readable(
                lambda: (
                    len(
                        vectors.get_vectors(
                            vectorBucketName=self._config["vectorBucket"],
                            indexName=self._config["vectorIndex"],
                            keys=[vector_key(subject["subjectRef"], 0)],
                        ).get("vectors", [])
                    )
                    == 1
                ),
                what=f"vectors for {subject['subjectRef']}",
            )
        return {"vectors": count}

    def _write_analytics(self, subject: dict[str, Any], expected: dict[str, int]) -> dict[str, int]:
        rows = expected.get("rows", 0)
        if rows:
            # A multi-row INSERT ... VALUES cannot be parameterised, so the handle is
            # validated against the pseudonymous-reference shape before it is interpolated.
            # That is the mechanism behind the suppression below; without it, "the seed file
            # is trusted" would be an assertion with nothing enforcing it.
            handle = _safe_handle(subject["subjectRef"])
            # Iceberg INSERT appends. Without this the row count doubles per run and the
            # ground-truth map silently understates what discovery will find.
            self._athena(
                f"DELETE FROM {self._config['analyticsTable']} "  # noqa: S608
                f"WHERE subject_ref = '{handle}'"
            )
            values = ", ".join(f"('{handle}', 'event-{n}')" for n in range(rows))
            self._athena(
                f"INSERT INTO {self._config['analyticsTable']} (subject_ref, event) "  # noqa: S608
                f"VALUES {values}"
            )
        return {"rows": rows}

    def _write_suppression(
        self, subject: dict[str, Any], expected: dict[str, int]
    ) -> dict[str, int]:
        ses = self._clients["sesv2"]
        address = subject_address(subject["subjectRef"])
        if expected.get("contacts"):
            try:
                ses.create_contact(
                    ContactListName=self._config["contactList"], EmailAddress=address
                )
            except ClientError as error:
                if error.response["Error"]["Code"] != "AlreadyExistsException":
                    raise
        if expected.get("suppressionEntries"):
            ses.put_suppressed_destination(EmailAddress=address, Reason="COMPLAINT")
        return {
            "contacts": expected.get("contacts", 0),
            "suppressionEntries": expected.get("suppressionEntries", 0),
        }

    # ── plumbing ─────────────────────────────────────────────────────────────────────

    def _sql(self, statement: str, **params: Any) -> Any:
        # Same helper the participant uses. The seeder is usually the *first* thing to
        # touch a freshly deployed cluster, so it meets the auto-pause resume before
        # anything else does — and defining the wait twice would let the two drift.
        return execute_with_resume(
            self._clients["rds-data"],
            resourceArn=self._config["billingClusterArn"],
            secretArn=self._config["billingSecretArn"],
            database=self._config["billingDatabase"],
            sql=statement,
            parameters=[
                {"name": name, "value": {"stringValue": str(value)}}
                if not isinstance(value, int)
                else {"name": name, "value": {"longValue": value}}
                for name, value in params.items()
            ],
        )

    def _athena(self, statement: str) -> str:
        athena = self._clients["athena"]
        started = athena.start_query_execution(
            QueryString=statement,
            QueryExecutionContext={"Database": self._config["analyticsDatabase"]},
            WorkGroup=self._config["athenaWorkgroup"],
        )
        execution_id: str = started["QueryExecutionId"]
        _await_readable(
            lambda: (
                athena.get_query_execution(QueryExecutionId=execution_id)["QueryExecution"][
                    "Status"
                ]["State"]
                == "SUCCEEDED"
            ),
            what=f"athena statement {execution_id}",
        )
        return execution_id


#: Pseudonymous handles are generated by this repo and look like `sub_mar_7f3a91c4`.
#: Anything else is either a bug or an injection attempt, and both should stop here.
_HANDLE = re.compile(r"^[a-z0-9_]{3,64}$")


def _safe_handle(subject_ref: str) -> str:
    if not _HANDLE.match(subject_ref):
        raise ValueError(
            f"subjectRef {subject_ref!r} is not a pseudonymous handle — refusing to "
            "interpolate it into a statement"
        )
    return subject_ref


def _purge_versions(s3: Any, bucket: str, prefix: str) -> int:
    """Remove every version and delete marker under `prefix`. Returns how many.

    Deliberately version-scoped: `delete_object` on a versioned bucket writes a delete
    marker and removes nothing, which is the lesson `upload-bucket` exists to teach. A
    seeder that fell for it would leave the previous run's objects in place *and* add a
    marker, so the count would grow in two dimensions at once.
    """
    removed = 0
    paginator = s3.get_paginator("list_object_versions")
    for page in paginator.paginate(Bucket=bucket, Prefix=prefix):
        targets = [
            {"Key": entry["Key"], "VersionId": entry["VersionId"]}
            for entry in page.get("Versions", []) + page.get("DeleteMarkers", [])
        ]
        for start in range(0, len(targets), 1000):  # DeleteObjects caps at 1000
            s3.delete_objects(
                Bucket=bucket, Delete={"Objects": targets[start : start + 1000], "Quiet": True}
            )
        removed += len(targets)
    return removed


def _exists(call: Callable[[], Any]) -> bool:
    try:
        call()
    except Exception:
        return False
    return True


def expected_systems(seeds: dict[str, Any]) -> dict[str, set[str]]:
    """What the seed file *claims*, for cross-checking against what was written.

    Deliberately separate from `GroundTruth`: this reads the declaration, that records the
    action. `make seed` compares them, and a mismatch means the generator silently failed to
    write something — which would otherwise surface much later as an unexplained recall miss.
    """
    return {
        subject["subjectRef"]: set(subject.get("placement", {})) for subject in seeds["subjects"]
    }


def reconcile(truth: GroundTruth, seeds: dict[str, Any]) -> list[str]:
    """Differences between what the seeds declared and what the generator actually wrote."""
    problems: list[str] = []
    for subject_ref, declared in expected_systems(seeds).items():
        actual = truth.systems_for(subject_ref)
        for missing in sorted(declared - actual):
            problems.append(f"{subject_ref}: declared in {missing} but nothing was written")
        for extra in sorted(actual - declared):
            problems.append(f"{subject_ref}: written to {extra} but not declared in seeds")
    return problems


def iter_subject_refs(seeds: dict[str, Any]) -> Iterable[str]:
    return (subject["subjectRef"] for subject in seeds["subjects"])
