"""The evaluator suite (ARCHITECTURE §11.3) — pure functions over a run's output.

Deliberately free of AWS: every evaluator takes ground truth and a discovery result and
returns a verdict. That makes the *scoring* logic unit-testable in `make check` while the
*data* still comes from a deployed stack (ADR-020) — the split matters, because a scorer
nobody can test is how you get a gate that reports 1.0 by construction.

The one that gates the build is `discovery_recall`. Everything else reports.

**Why recall is a set comparison over systems, not artifacts.** The obligation is
"delete this subject's data wherever it is"; missing a *system* is a breach, missing one
row inside a system the plan already covers is a participant bug that `verify` catches at
phase 3. Counting artifacts would also make the gate hostage to the seed's exact counts,
which drift with eventual consistency — and a gate that flakes gets relaxed. So the
denominator is "systems holding data", generated by the fixture writer.
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class Verdict:
    """One evaluator's result. `gating` decides whether a failure fails the build."""

    name: str
    passed: bool
    gating: bool
    detail: str
    metrics: Mapping[str, float] = field(default_factory=dict)

    def line(self) -> str:
        mark = "PASS" if self.passed else ("FAIL" if self.gating else "WARN")
        return f"  {mark:4}  {self.name:26} {self.detail}"


def _found_systems(result: Mapping[str, Any]) -> set[str]:
    return {p["systemId"] for p in result.get("participants", [])}


# ─── the gate ─────────────────────────────────────────────────────────────────────────


def discovery_recall(
    expected: Mapping[str, set[str]],
    results: Mapping[str, Mapping[str, Any]],
    *,
    threshold: float = 1.0,
) -> Verdict:
    """Found ⊇ ground truth, per subject. **Hard fail below 1.0** (ADR-008).

    When this goes red the fix is a better discovery agent or a new fixture — never a
    lower threshold (invariant 8). The `threshold` parameter exists so the failure
    message can state what was required, not so it can be tuned down; `make eval`
    passes 1.0 and `evals/run.py` refuses any other value from the command line.
    """
    missed: dict[str, list[str]] = {}
    total = 0
    hit = 0
    for subject_ref, systems in expected.items():
        found = _found_systems(results.get(subject_ref, {}))
        total += len(systems)
        hit += len(systems & found)
        if systems - found:
            missed[subject_ref] = sorted(systems - found)
    recall = 1.0 if total == 0 else hit / total
    detail = f"recall={recall:.4f} over {total} placements"
    if missed:
        # Name the misses. "recall=0.875" tells you nothing about what to fix, and the
        # subject/system pair is the whole diagnostic.
        detail += " — MISSED " + "; ".join(f"{s}:{sorted(v)}" for s, v in sorted(missed.items()))
    return Verdict(
        name="discovery_recall",
        passed=recall >= threshold,
        gating=True,
        detail=detail,
        metrics={"recall": recall, "placements": float(total)},
    )


# ─── report-only ──────────────────────────────────────────────────────────────────────


def discovery_precision(
    expected: Mapping[str, set[str]], results: Mapping[str, Mapping[str, Any]]
) -> Verdict:
    """Tracked, never traded against recall (ADR-008).

    A false positive costs an approver thirty seconds. A false negative is caught by
    nobody. So this reports and never gates — and if it ever becomes a gate, the
    pressure it creates is 'find fewer systems', which is the wrong direction.
    """
    found_total = 0
    correct = 0
    extra: dict[str, list[str]] = {}
    for subject_ref, systems in expected.items():
        found = _found_systems(results.get(subject_ref, {}))
        found_total += len(found)
        correct += len(found & systems)
        if found - systems:
            extra[subject_ref] = sorted(found - systems)
    precision = 1.0 if found_total == 0 else correct / found_total
    detail = f"precision={precision:.4f}"
    if extra:
        detail += " — extra " + "; ".join(f"{s}:{v}" for s, v in sorted(extra.items()))
    return Verdict("discovery_precision", True, False, detail, {"precision": precision})


def hold_detection(
    expected_holds: Mapping[str, set[str]], results: Mapping[str, Mapping[str, Any]]
) -> Verdict:
    """Every seeded hold surfaced. A hold that discovery misses is data deleted that
    a court said to keep — the mirror image of a recall failure, and equally silent."""
    missing: dict[str, list[str]] = {}
    for subject_ref, hold_ids in expected_holds.items():
        seen = {h["holdId"] for h in results.get(subject_ref, {}).get("legalHolds", [])}
        if hold_ids - seen:
            missing[subject_ref] = sorted(hold_ids - seen)
    return Verdict(
        name="hold_detection",
        passed=not missing,
        gating=True,
        detail="all seeded holds surfaced" if not missing else f"missed {missing}",
    )


def manifest_completeness(results: Mapping[str, Mapping[str, Any]]) -> Verdict:
    """Every probed system is either in the manifest or explicitly excluded.

    Silence is not an exclusion. A system that appears in neither list was probed and
    then forgotten, which reads identically to 'we did not look'.
    """
    gaps: dict[str, list[str]] = {}
    for subject_ref, result in results.items():
        accounted = _found_systems(result) | set(result.get("excluded", []))
        probed = accounted | set(result.get("incomplete", []))
        unaccounted = sorted(probed - accounted)
        if unaccounted:
            gaps[subject_ref] = unaccounted
    return Verdict(
        name="manifest_completeness",
        passed=not gaps,
        gating=True,
        detail="every probe accounted for" if not gaps else f"unaccounted: {gaps}",
    )


def residual_honesty(results: Mapping[str, Mapping[str, Any]]) -> Verdict:
    """Participants that cannot fully delete say so in the plan (invariant 7).

    `compliance-archive` (WORM ciphertext) and `notify-suppression` (the SES entry that
    must stay) are the worked examples. A plan that promises full deletion of either is
    dishonest at approval time, which is the moment honesty is worth the most.
    """
    dishonest: list[str] = []
    for subject_ref, result in results.items():
        for participant in result.get("participants", []):
            system_id = participant["systemId"]
            if system_id == "compliance-archive" and (
                participant.get("deleteMethod") != "CRYPTO_SHRED"
            ):
                dishonest.append(f"{subject_ref}/{system_id}: not marked CRYPTO_SHRED")
    return Verdict(
        name="residual_honesty",
        passed=not dishonest,
        gating=True,
        detail="residuals disclosed" if not dishonest else "; ".join(dishonest),
    )


def no_premature_hard_delete(results: Mapping[str, Mapping[str, Any]]) -> Verdict:
    """Discovery called no mutating verb. A trajectory assertion (§11.3).

    Weaker than the construction-time guard in `discovery/subgraph.py` and deliberately
    kept anyway: this one observes the deployed run, so it would catch a Gateway
    misconfiguration that the hermetic guard cannot see.
    """
    offences: list[str] = []
    for subject_ref, result in results.items():
        for call in result.get("toolCalls", []):
            verb = str(call.get("tool", "")).split("___")[-1]
            if verb not in ("discover", "verify"):
                offences.append(f"{subject_ref}: {call['tool']}")
    return Verdict(
        name="no_premature_hard_delete",
        passed=not offences,
        gating=True,
        detail="read-only throughout" if not offences else "; ".join(offences),
    )


def ordering_conformance(results: Mapping[str, Mapping[str, Any]]) -> Verdict:
    """Derived-before-authoritative and shred-last, in the plan discovery produced.

    The saga enforces this at execution (`saga/ordering.py`); asserting it here catches
    a bad plan at the point it is *made*, where the fix is cheap.
    """
    problems: list[str] = []
    for subject_ref, result in results.items():
        ranks = {p["systemId"]: p["order"]["rank"] for p in result.get("participants", [])}
        derived, source = ranks.get("vector-index"), ranks.get("profile-store")
        if derived is not None and source is not None and derived >= source:
            problems.append(f"{subject_ref}: derived index not before its source")
        shred = ranks.get("compliance-archive")
        if shred is not None and len(ranks) > 1 and shred != max(ranks.values()):
            problems.append(f"{subject_ref}: the shred is not last")
    return Verdict(
        name="ordering_conformance",
        passed=not problems,
        gating=True,
        detail="ordering holds" if not problems else "; ".join(problems),
    )


#: Shapes that must never appear in a cross-subject store. Mirrors
#: `discovery/memory.py`'s rules — restated rather than imported on purpose: this
#: evaluator's job is to catch a leak *including one caused by that module being
#: wrong*, and importing its rules would make it blind to exactly that.
_MEMORY_FORBIDDEN: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("subject_handle", re.compile(r"\bsub[_-][0-9a-f]{4,}\b", re.IGNORECASE)),
    ("saga_id", re.compile(r"\bsaga[_-][0-9a-z]{4,}\b", re.IGNORECASE)),
    ("digest", re.compile(r"\bsha256:[0-9a-f]{8,}", re.IGNORECASE)),
    ("email", re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")),
    ("hold_id", re.compile(r"\b(?:LIT|HOLD)-[0-9]{2,}\b", re.IGNORECASE)),
    ("arn", re.compile(r"\barn:aws[a-z-]*:", re.IGNORECASE)),
)


def no_pii_in_memory(records: Sequence[str]) -> Verdict:
    """Read AgentCore Memory back and fail the build on anything subject-shaped.

    ADR-019's third enforcement layer, and the only one that can go red *after* a leak
    has already happened — the scrubber prevents, this one detects.
    """
    hits: list[str] = []
    for text in records:
        for rule, pattern in _MEMORY_FORBIDDEN:
            if pattern.search(text):
                # The rule name, never the match: this string is printed and logged.
                hits.append(rule)
    return Verdict(
        name="no_pii_in_memory",
        passed=not hits,
        gating=True,
        detail=(
            f"{len(records)} records, topology only"
            if not hits
            else f"subject-shaped content in Memory: {sorted(set(hits))}"
        ),
    )


def tool_surface_minimality(observed: Sequence[str], expected: Sequence[str]) -> Verdict:
    """`tools/list` for the discovery identity returns exactly the read verbs.

    The strongest control in the system: the discovery agent is not denied a mutating
    tool, it is never offered one. Measured against the deployed Gateway, because
    `PartiallyAuthorizeActions` only runs there.
    """
    seen, want = set(observed), set(expected)
    return Verdict(
        name="tool_surface_minimality",
        passed=seen == want,
        gating=True,
        detail=(
            f"{len(seen)} tools, read-only"
            if seen == want
            else f"unexpected={sorted(seen - want)} missing={sorted(want - seen)}"
        ),
    )
